-- 03_governance.sql: policies, views, grants. Run as BB_ADMIN.
-- Users are created by bootstrap.py (passwords are generated and kept in .env).
USE ROLE BB_ADMIN;
USE WAREHOUSE BB_WH;
USE SCHEMA BEAN_BREW.CORE;

-- ROW ACCESS: the tool sets session variables from the *signed* WXO context
-- (BB_STORE_ID, BB_REGION) and Snowflake enforces them, even if the tool's SQL is wrong.
CREATE OR REPLACE ROW ACCESS POLICY RAP_SCOPE AS (store_id STRING, region STRING) RETURNS BOOLEAN ->
  CASE
    WHEN CURRENT_ROLE() IN ('BB_ADMIN', 'ACCOUNTADMIN', 'SYSADMIN', 'BB_FINANCE', 'BB_HR') THEN TRUE
    WHEN CURRENT_ROLE() IN ('BB_BARISTA', 'BB_MANAGER') THEN store_id = GETVARIABLE('BB_STORE_ID')
    WHEN CURRENT_ROLE() = 'BB_REGIONAL' THEN region = GETVARIABLE('BB_REGION')
    ELSE FALSE
  END;

ALTER TABLE SALES ADD ROW ACCESS POLICY RAP_SCOPE ON (store_id, region);
ALTER TABLE INVENTORY ADD ROW ACCESS POLICY RAP_SCOPE ON (store_id, region);
ALTER TABLE EMPLOYEES ADD ROW ACCESS POLICY RAP_SCOPE ON (store_id, region);

-- COLUMN MASKING: only HR (and the owner) sees salary and contact details.
CREATE OR REPLACE MASKING POLICY MASK_SALARY AS (v NUMBER) RETURNS NUMBER ->
  CASE WHEN CURRENT_ROLE() IN ('BB_HR', 'BB_ADMIN', 'ACCOUNTADMIN') THEN v ELSE NULL END;

CREATE OR REPLACE MASKING POLICY MASK_EMAIL AS (v STRING) RETURNS STRING ->
  CASE WHEN CURRENT_ROLE() IN ('BB_HR', 'BB_ADMIN', 'ACCOUNTADMIN') THEN v
       ELSE REGEXP_REPLACE(v, '^[^@]+', '*****') END;

CREATE OR REPLACE MASKING POLICY MASK_PHONE AS (v STRING) RETURNS STRING ->
  CASE WHEN CURRENT_ROLE() IN ('BB_HR', 'BB_ADMIN', 'ACCOUNTADMIN') THEN v
       ELSE '***-***-' || RIGHT(v, 4) END;

ALTER TABLE EMPLOYEES MODIFY COLUMN salary SET MASKING POLICY MASK_SALARY;
ALTER TABLE EMPLOYEES MODIFY COLUMN email SET MASKING POLICY MASK_EMAIL;
ALTER TABLE EMPLOYEES MODIFY COLUMN phone SET MASKING POLICY MASK_PHONE;

-- AGGREGATE VIEWS for finance: they never see raw salaries or individual orders.
CREATE OR REPLACE SECURE VIEW SALES_DAILY AS
  SELECT DATE(ts) AS day, store_id, region, product, SUM(qty) AS units, SUM(amount) AS revenue
  FROM SALES GROUP BY 1, 2, 3, 4;

-- Salary aggregates are computed by the owner's rights through a view over a private table copy,
-- so BB_FINANCE can see averages without any access to EMPLOYEES.
CREATE OR REPLACE TABLE _SALARY_FACTS AS
  SELECT store_id, region, role, COUNT(*) AS headcount, AVG(salary) AS avg_salary, SUM(salary) AS total_salary
  FROM EMPLOYEES GROUP BY 1, 2, 3;
CREATE OR REPLACE SECURE VIEW SALARY_SUMMARY AS SELECT * FROM _SALARY_FACTS;

-- GRANTS (least privilege, matches the RBAC matrix in docs/rbac.md)
GRANT USAGE ON WAREHOUSE BB_WH TO ROLE BB_BARISTA;
GRANT USAGE ON WAREHOUSE BB_WH TO ROLE BB_MANAGER;
GRANT USAGE ON WAREHOUSE BB_WH TO ROLE BB_REGIONAL;
GRANT USAGE ON WAREHOUSE BB_WH TO ROLE BB_FINANCE;
GRANT USAGE ON WAREHOUSE BB_WH TO ROLE BB_HR;

GRANT USAGE ON DATABASE BEAN_BREW TO ROLE BB_BARISTA;
GRANT USAGE ON DATABASE BEAN_BREW TO ROLE BB_MANAGER;
GRANT USAGE ON DATABASE BEAN_BREW TO ROLE BB_REGIONAL;
GRANT USAGE ON DATABASE BEAN_BREW TO ROLE BB_FINANCE;
GRANT USAGE ON DATABASE BEAN_BREW TO ROLE BB_HR;
GRANT USAGE ON SCHEMA BEAN_BREW.CORE TO ROLE BB_BARISTA;
GRANT USAGE ON SCHEMA BEAN_BREW.CORE TO ROLE BB_MANAGER;
GRANT USAGE ON SCHEMA BEAN_BREW.CORE TO ROLE BB_REGIONAL;
GRANT USAGE ON SCHEMA BEAN_BREW.CORE TO ROLE BB_FINANCE;
GRANT USAGE ON SCHEMA BEAN_BREW.CORE TO ROLE BB_HR;

GRANT SELECT ON TABLE STORES TO ROLE BB_BARISTA;
GRANT SELECT ON TABLE STORES TO ROLE BB_MANAGER;
GRANT SELECT ON TABLE STORES TO ROLE BB_REGIONAL;
GRANT SELECT ON TABLE STORES TO ROLE BB_FINANCE;
