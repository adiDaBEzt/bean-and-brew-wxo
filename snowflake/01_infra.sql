-- 01_infra.sql: warehouse, database, roles. Run as ACCOUNTADMIN.
-- SAFETY: this file never touches existing users, account-level parameters or network policies.

CREATE WAREHOUSE IF NOT EXISTS BB_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS BEAN_BREW;
CREATE SCHEMA IF NOT EXISTS BEAN_BREW.CORE;

CREATE ROLE IF NOT EXISTS BB_ADMIN;
CREATE ROLE IF NOT EXISTS BB_BARISTA;
CREATE ROLE IF NOT EXISTS BB_MANAGER;
CREATE ROLE IF NOT EXISTS BB_REGIONAL;
CREATE ROLE IF NOT EXISTS BB_FINANCE;
CREATE ROLE IF NOT EXISTS BB_HR;

-- Hierarchy: the project owner role rolls up to SYSADMIN, so ACCOUNTADMIN keeps full control.
GRANT ROLE BB_BARISTA  TO ROLE BB_ADMIN;
GRANT ROLE BB_MANAGER  TO ROLE BB_ADMIN;
GRANT ROLE BB_REGIONAL TO ROLE BB_ADMIN;
GRANT ROLE BB_FINANCE  TO ROLE BB_ADMIN;
GRANT ROLE BB_HR       TO ROLE BB_ADMIN;
GRANT ROLE BB_ADMIN    TO ROLE SYSADMIN;

GRANT OWNERSHIP ON DATABASE BEAN_BREW TO ROLE BB_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA BEAN_BREW.CORE TO ROLE BB_ADMIN COPY CURRENT GRANTS;
GRANT USAGE, OPERATE ON WAREHOUSE BB_WH TO ROLE BB_ADMIN;
